# 01-02 Your first program

# Example 1: print shows a value on the screen
print("Hello, world!")
print(42)
print(3.5)

# Example 2: print can take several values, separated by commas
print("I am", 30, "years old")

# Example 3: sep and end change what goes between and after the values
print("2026", "11", "11", sep="-")
print("Loading", end="...")
print("done")

# Example 4: an empty print() prints a blank line
print("Above the gap")
print()
print("Below the gap")

# Example 5: comments are ignored by Python
# This whole line is a comment.
print("Comments do not run")  # this part of the line is a comment too
# print("This line is switched off")

# Example 6: statements run from top to bottom
print("Step 1: boil the water")
print("Step 2: add the pasta")
print("Step 3: drain and serve")
